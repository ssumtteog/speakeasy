#!/usr/bin/env python3
"""Bundle ../speakeasy web assets into src/generated/speakeasyHtml.ts."""

import base64
import json
import mimetypes
import re
from pathlib import Path

EXPO_DIR = Path(__file__).resolve().parent.parent
WEB_DIR = EXPO_DIR.parent / "web"
OUT_FILE = EXPO_DIR / "src" / "generated" / "speakeasyHtml.ts"


def inline_assets(text: str) -> str:
    def replace_asset(match: re.Match) -> str:
        rel_path = match.group(1)
        asset_path = WEB_DIR / rel_path
        if not asset_path.is_file():
            return match.group(0)
        mime, _ = mimetypes.guess_type(str(asset_path))
        mime = mime or "application/octet-stream"
        b64 = base64.b64encode(asset_path.read_bytes()).decode("ascii")
        return f"data:{mime};base64,{b64}"

    return re.sub(r"(assets/[A-Za-z0-9_./-]+\.(?:jpg|jpeg|png|webp|svg))", replace_asset, text)


def main() -> None:
    html = (WEB_DIR / "index.html").read_text(encoding="utf-8")

    def replace_css(match: re.Match) -> str:
        href = match.group(1)
        css_text = (WEB_DIR / href).read_text(encoding="utf-8")
        css_text = inline_assets(css_text)
        return f'<style data-src="{href}">\n{css_text}\n  </style>'

    def replace_js(match: re.Match) -> str:
        src = match.group(1)
        js_text = (WEB_DIR / src).read_text(encoding="utf-8")
        js_text = inline_assets(js_text)
        js_text = js_text.replace("</script>", "<\\/script>")
        return f'<script data-src="{src}">\n{js_text}\n  </script>'

    html = re.sub(r'<link\s+rel="stylesheet"\s+href="([^"]+)">', replace_css, html)
    html = re.sub(r'<script\s+src="([^"]+)"></script>', replace_js, html)
    html = inline_assets(html)

    import hashlib
    rev = hashlib.sha1(html.encode("utf-8")).hexdigest()[:10]
    out = (
        "// Auto-generated by scripts/bundle-speakeasy.py — do not edit manually\n"
        f"export const SPEAKEASY_HTML_VERSION = {json.dumps(rev)};\n"
        f"export const SPEAKEASY_HTML: string = {json.dumps(html, ensure_ascii=False)};\n"
    )
    OUT_FILE.write_text(out, encoding="utf-8")
    print(f"Bundled {OUT_FILE} ({len(out):,} bytes)")


if __name__ == "__main__":
    main()
